/**
 * Acepta una clave suelta (`"memoriaTerritorial2016"`) o una clave con resumen y
 * límite propios del mito (`{ key, summary, limitation }`). La ficha
 * bibliográfica la fija el pool; lo que cambia por mito es qué dice esa obra
 * sobre ese relato.
 */
export function pickPananSources(...entries) {
  const vistas = new Set();
  const salida = [];
  for (const entrada of entries) {
    const key = typeof entrada === "string" ? entrada : entrada?.key;
    const source = pananSources[key];
    if (!source) {
      const visto = typeof entrada === "string" ? entrada : JSON.stringify(entrada);
      throw new Error(`Fuente de Panán desconocida: ${visto}.`);
    }
    if (vistas.has(key)) continue;
    vistas.add(key);
    salida.push(
      typeof entrada === "string"
        ? source
        : {
            ...source,
            ...(entrada.summary ? { summary: entrada.summary } : {}),
            ...(entrada.limitation ? { limitation: entrada.limitation } : {}),
          },
    );
  }
  return salida;
}

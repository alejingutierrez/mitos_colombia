const mito = `Kuriruputá era un hombre rico. Tenía tantos animales y andaba tan bien puesto que brillaba como el sol. Su casa quedaba en Matumuy, con los corrales de los novillos y de las vacas de ordeño a un lado.

Unos kosinas salieron en busca de animales. Llegaron a la laguna de Kuitsá y allí esperaron, quietos entre los cardones, hasta que se ocultó el sol. Solo entonces siguieron su marcha. A las nueve de la noche estaban en Matumuy. Encontraron los animales encerrados, abrieron un hueco en el costado opuesto a la puerta, sacaron algunos de los mejores novillos y volvieron a cerrar la cerca.

Entre los animales había un novillo muy bravo. Corrió detrás de los kosinas y ellos huyeron.

—Mejor será dejarlos.

Abrieron entonces el corral de las vacas de ordeño y se las llevaron, pero las vacas no corrían ni querían caminar. A empujones las arriaron hasta la laguna de Kuitsá, y allí pasaron la noche.

Cuando el novillo comenzó a bramar, el dueño se despertó. Recogió los animales que los kosinas no habían podido llevarse y, como había luna, vio las huellas sobre la arena. Llamó a toda la gente, despertó a todos, pero solo vinieron las mujeres: no había más hombres.

—Yo me alistaré y seguiré atrás de los animales —les dijo.

Se fajó el revólver, cargó el rifle y se puso a la cintura tres fajones llenos de balas.

Les dio alcance en la laguna. Corrió hacia el cerro para salirles adelante y les cortó el paso. Los kosinas lo divisaron.

—Allá está. Mejor matémoslo.

Le tiraron. Las balas pasaban junto a él sin herirlo. Cuando todos hubieron disparado, Kuriruputá habló.

—Ahora tiraré yo.

Al primer disparo mató a un kosina. Mientras tanto las vacas, solas, tomaban el camino de su casa. Kuriruputá las siguió y los kosinas lo siguieron a él. Por fin uno le pegó en la pierna y le desastilló la rodilla. Apoyado en la otra pierna, Kuriruputá se volvió hacia ellos, disparó el revólver y el rifle y mató a dos. Los kosinas vieron que estaba herido y decidieron acercarse para rematarlo. Él tomó el revólver en una mano y el rifle en la otra y mató a otros dos. Le tiraron flechas iguarayo; no le pegaban. Disparó otra vez y cayó otro kosina.

Entonces, a lo lejos, aparecieron sus hermanas. Traían un rifle y un pañuelo de cuatro varas, porque creían que estaría muerto y venían a recoger el cadáver. Lo primero que encontraron fueron las vacas que regresaban; después, las huellas de sangre del hermano. Cuando dieron con él ya casi no tenía fuerzas. Le amarraron la herida de la pierna y lo llevaron a un cerrito.

Las mujeres siguieron persiguiendo a los kosinas. Estos, al darse cuenta de que eran mujeres, se dijeron:

—Vamos a cogerlas. Las tendremos por nuestras mujeres.

Marcharon hacia ellas. Pero las hermanas se armaron y cada una mató a un kosina; otros intentaron cogerlas y también murieron. Los que quedaban se miraron.

—Son muy bravas. Es mejor que huyamos.

Las mujeres los persiguieron sin darles alcance. Solo entonces volvieron a atender al hermano y lo llevaron a la casa.

Aquella noche, tendido en el chinchorro con la rodilla rota, Kuriruputá soñó que alguien le hablaba.

—Para que te sanes, trágate una contra y una tuma. Toma por mujer a una de tus criadas y abandona a la que tienes. Solamente así vivirás mucho tiempo.

Tan pronto despertó, hizo tal cual lo había soñado. Y el sueño se cumplió: Kuriruputá sanó y vivió muchos años.`;

const historia = `El cuento aparece en «Mitos, leyendas y cuentos de la Guajira», que Milcíades Chaves publicó en 1946 en el Boletín de Arqueología, como el décimo de quince textos recogidos para el Instituto Etnológico Nacional. Su última línea dice que «el indio Kuriruputá murió el año pasado»: estamos ante la memoria de un hombre real, muerto hacia 1945, contada por sus contemporáneos, y no ante un tiempo de origen. Chaves parece referirse a este texto cuando en su introducción habla de «una tradición en trance de convertirse en cuento», donde «la realidad de los hechos y la fantasía del relator corren parejas» y donde el guajiro cree en el sueño «con fe de carbonero» y cumple sus órdenes. La nota de informante que cierra el bloque anterior (Juancito Iguarán, casta Pushaina, con Roberto Iguarán como intérprete) no cubre con certeza este cuento; el expediente no le asigna un narrador propio.

La vida material que describe es la de la Alta Guajira del siglo XX temprano: corrales de novillos y de vacas de ordeño, revólver, rifle y fajones de balas de un lado, flechas iguarayo del otro. Los «kosinas» que asaltan el corral no son una etnia fija. Michel Perrin explica que hasta el siglo XIX el término kusina designaba a quienes saqueaban y robaban a los guajiros vecinos, y que hoy nombra a otros indios o a wayuu pobres de zonas remotas que no criaban ganado. José Polo Acuña sitúa el fondo histórico en el siglo XVIII: los Wayúu que expandían el ganado frente a los Cocinas que defendían el territorio y rechazaban esa expansión. Weildler Guerra Curvelo señala el hurto de ganado como una de las tres causas mayores de enfrentamiento entre familias, con tres salidas posibles: abstenerse, vengarse o exigir compensación por medio del palabrero. Kuriruputá no lo toma: sale solo, con las armas.

Las hermanas que llegan con un pañuelo de cuatro varas para amortajarlo y terminan combatiendo tienen un respaldo etnográfico parcial. Clara Viviana Rúa Bustamante y otros documentan en la Media y Alta Guajira que las mujeres son en gran parte las poseedoras de los animales y que resolver conflictos por robo de ganado está entre sus funciones; ese estudio no habla de mujeres combatientes, y el cuento sí. Roberto Pineda Giraldo transcribió en 1950 una representación teatral de la guerra interclanil en la que los bandos se amenazan con tomar «a tus mujeres y a tus hijos y sobrinos como esclavos»; la intención de los kosinas de quedarse con las hermanas «por nuestras mujeres» pertenece a ese mismo horizonte.

El sueño final encaja en lo que Pineda llamó sueños «reales»: mensajes tan explícitos que no necesitan interpretación, «como una conversación entre el individuo y el espíritu» que le dice qué tomar para curarse. Dos cautelas. La primera: la contra y la tuma son remedio y joya de valor en la Guajira, y Francisco Molina Ríos lee el rojo y la represalia dentro de un orden simbólico wayuu, pero el cuento no explica la tuma; esta edición tampoco. La segunda: «toma por mujer a una de tus criadas y abandona a la que tienes» es la orden del sueño tal como la tradujo Chaves. La palabra «criada» pertenece a su vocabulario y a la realidad de dependencia que él mismo describe al hablar de castas vencidas cuyos miembros «pasan a ser sus esclavos»; no la suavizamos ni la explicamos con normas actuales. La ficha anterior había sustituido esa orden por una mediación y una deliberación con las hermanas que Chaves no cuenta.`;

